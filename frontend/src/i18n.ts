import WebApp from '@twa-dev/sdk'
import { initData } from './telegram'

// Язык интерфейса берем из Telegram пользователя. Русский - для ru/uk/be/kk, остальным английский.
export type Lang = 'ru' | 'en';

function telegramLanguageCode(): string | undefined {
  const fromSdk = (WebApp as unknown as { initDataUnsafe?: { user?: { language_code?: string } } })
    .initDataUnsafe?.user?.language_code;
  if (fromSdk) return fromSdk;
  try {
    // Без скрипта Telegram язык есть в подписанных данных initData (поле user)
    const user = new URLSearchParams(initData).get('user');
    return user ? (JSON.parse(user) as { language_code?: string }).language_code : undefined;
  } catch {
    return undefined;
  }
}

const STORAGE_KEY = 'ui-lang';

// Сначала язык, выбранный вручную (RU / EN в приложении или /language в боте), потом язык Telegram
function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'ru' || saved === 'en') return saved;
  } catch {
    // хранилище недоступно
  }
  const code = (telegramLanguageCode() ?? navigator.language ?? 'ru').toLowerCase().split('-')[0];
  return ['ru', 'uk', 'be', 'kk'].includes(code) ? 'ru' : 'en';
}

/** Запоминает язык на этом устройстве; применяется после перезагрузки приложения. */
export function rememberLang(value: Lang): boolean {
  try {
    localStorage.setItem(STORAGE_KEY, value);
    return localStorage.getItem(STORAGE_KEY) === value;
  } catch {
    // хранилище недоступно: перезагрузка не поможет, остаемся на текущем языке
    return false;
  }
}

